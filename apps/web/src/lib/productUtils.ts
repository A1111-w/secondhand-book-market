/**
 * 温莎化求平均值
 * @param numbers 数字数组
 * @param trimPercent 裁剪百分比（例如 0.05 表示裁剪掉头尾各 5% 的数据）
 * @returns 返回处理后的平均值
 */
export const getWinsorizedAverage = (numbers: number[], trimPercent: number = 0.05): number => {
  if (numbers.length === 0) return 0;

  const sorted = [...numbers].sort((a, b) => a - b);
  const lowIndex = Math.floor(numbers.length * trimPercent);
  const highIndex = Math.ceil(numbers.length * (1 - trimPercent)) - 1;

  const lowerBound = sorted[lowIndex];
  const upperBound = sorted[highIndex];

  const trimmed = sorted.map(n => {
    if (n < lowerBound) return lowerBound;
    if (n > upperBound) return upperBound;
    return n;
  });

  const sum = trimmed.reduce((acc, val) => acc + val, 0);
  return sum / trimmed.length;
};